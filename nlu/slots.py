NEEDS_CASE_FIX = {"open_app", "close_app", "open_website"}

_TRAIL = re.compile(
    r"\s+(?:в интернете|в гугле|в браузере|на ютубе|в ютубе|на youtube|пожалуйста|сейчас|быстро|прямо сейчас)$"
)


def _fix_accusative(phrase: str) -> str:
    """«доту» → «дота», «оперу» → «опера», «википедию» → «википедия»."""
    words = []
    for word in phrase.split():
        if re.fullmatch(r"[а-яё]{3,}у", word):
            word = word[:-1] + "а"
        elif re.fullmatch(r"[а-яё]{3,}ю", word):
            word = word[:-1] + "я"
        words.append(word)
    return " ".join(words)


def extract_query(label: str, text: str) -> str:
    lead = LEAD.get(label)
    if lead is None:
        return ""
    stop = lead | COMMON_LEAD

    words = text.split()
    i = 0
    while i < len(words) and words[i] in stop:
        i += 1
    query = " ".join(words[i:])

    # хвост может быть из нескольких служебных фраз: «... в интернете пожалуйста»
    while True:
        stripped = _TRAIL.sub("", query).strip()
        if stripped == query:
            break
        query = stripped

    if label in NEEDS_CASE_FIX:
        query = _fix_accusative(query)
    return query
