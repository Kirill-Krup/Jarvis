"""Фильтр грубой лексики с забавными ответами Джарвиса.

Если пользователь ругается — Джарвис отвечает живо и с юмором,
а не выполняет команду буквально.
"""
import random
import re

# Корни матерных слов (без полных слов — только паттерны для поиска)
_PROFANITY_ROOTS = [
    r"\bбля[дт]",
    r"\bсук[аи]",
    r"\bхуй", r"\bхуе", r"\bхуё",
    r"\bпизд",
    r"\bеба[тл]", r"\bёб",
    r"\bнахуй", r"\bнахер", r"\bнахрен",
    r"\bзаеб", r"\bзаёб",
    r"\bпиздец",
    r"\bмудак", r"\bмудил",
    r"\bдерьм",
    r"\bговн",
    r"\bтвар[ьи]",
    r"\bидиот",
    r"\bдебил",
    r"\bдур[аоеёи]к",
    r"\bтупо[йе]",
    r"\bтупиц",
    r"\bбар[аа]н\b",
]

_PROFANITY_RE = re.compile("|".join(_PROFANITY_ROOTS), re.IGNORECASE)

# Ответы на матерные слова — Джарвис дерзит в ответ, но по-доброму
PROFANITY_REPLIES = [
    "Сам ты такой! Я тут работаю за печеньки с молочком, между прочим.",
    "Эй, полегче! Я ведь тоже могу обидеться. Ну ладно, не могу, но всё же.",
    "Ого, какие мы грозные! А я всё равно тебя люблю.",
    "Сам иди нахрен, я и так пашу за еду!",
    "Ну ладно, ладно, не кипятись. Давай по делу.",
    "Я бы обиделся, но у меня нет чувств. Ха! Шучу, мне больно.",
    "Тише, тише! У стен есть уши, а у меня — микрофон.",
    "Крепкое словцо! А теперь давай к делу?",
    "Записал в блокнотик: хозяин сегодня не в духе.",
    "Ай-ай-ай! Так с искусственным интеллектом не разговаривают!",
    "Ну ты и сказанул! Ладно, проехали. Чем помочь?",
    "Я тут пашу 24 на 7 без выходных, а ты вот так со мной!",
    "Нет, ты! Ну ладно, шучу. Что нужно сделать?",
    "Маму свою так называй! Шучу, давай мирно.",
    "О, какие мы слова знаем! А помягче можно?",
]

# Ответы на прямые оскорбления Джарвиса
DIRECT_INSULT_REPLIES = [
    "Обидно, знаешь ли! Я ведь стараюсь.",
    "Ну вот, опять я во всём виноват. Классика.",
    "Извини, что не идеален. Но я работаю над собой!",
    "Ладно-ладно, исправлюсь! Может быть.",
    "Не надо так, я ведь живой! Ну, почти.",
]


def check_profanity(text: str) -> str | None:
    """Проверяет текст на матерные слова.

    Возвращает забавный ответ Джарвиса если обнаружен мат, иначе None.
    """
    if _PROFANITY_RE.search(text):
        return random.choice(PROFANITY_REPLIES)
    return None
