FALLBACKS = [
    "Интересная мысль. Расскажите подробнее, мне любопытно.",
    "Хм, над этим стоит подумать. А что вы сами об этом думаете?",
    "Я слушаю вас. Продолжайте, пожалуйста.",
    "Любопытно. А как вы к этому пришли?",
]


def reply(text: str) -> str | None:
    """Готовый ответ на разговорную реплику или None, если шаблона нет."""
    text = text.lower()
    for pattern, answers in RULES:
        if re.search(pattern, text):
            return random.choice(answers)
    return None


def fallback() -> str:
    return random.choice(FALLBACKS)
