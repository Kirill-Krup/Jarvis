@skill(CATEGORY, "Случайное число в диапазоне",
       ["выбери число от 1 до 3", "случайное число от 1 до 100", "загадай число"],
       [r"\bчисл[оа]\b.*\bот\s+\d+\s+до\s+\d+", r"(?:загадай|случайное|назови)\s+(?:мне\s+)?(?:случайное\s+)?число"])
def random_number(cmd, ctx):
    m = re.search(r"от\s+(\d+)\s+до\s+(\d+)", cmd.text_lower)
    low, high = (int(m.group(1)), int(m.group(2))) if m else (1, 100)
    if low > high:
        low, high = high, low
    return ctx.reply(f"Выпало число {random.randint(low, high)}")


