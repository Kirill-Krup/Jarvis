def _known(ctx) -> set[str]:
    return ctx.app_launcher.known_names()


def _is_known(span: str, known: set[str]) -> bool:
    if span in known:
        return True
    return len(span) > 3 and (span[:-1] in known or span[:-1] + "а" in known)


def split_options(text: str, known: set[str]) -> list[str]:
    """«доту роблокс майнкрафт или геншин» -> [доту, роблокс, майнкрафт, геншин].

    Распознавание речи не ставит запятых, поэтому слитные названия
    разрезаются по известным программам и играм."""
    options: list[str] = []
    for chunk in re.split(r",|;|\sили\s|\sлибо\s|\sи\s", text):
        words = chunk.split()
        i, buffer = 0, []
        while i < len(words):
            for span_len in (3, 2, 1):
                span = " ".join(words[i:i + span_len])
                if len(words[i:i + span_len]) == span_len and _is_known(span, known):
                    if buffer:
                        options.append(" ".join(buffer))
                        buffer = []
                    options.append(span)
                    i += span_len
                    break
            else:
                buffer.append(words[i])
                i += 1
        if buffer:
            options.append(" ".join(buffer))
    return [o for o in options if o]


