@skill(CATEGORY, "Выбрать случайный вариант из названных и сразу запустить его",
       ["я не знаю во что поиграть, запусти мне доту, роблокс, майнкрафт или геншин",
        "выбери между пиццей и суши", "что выбрать чай или кофе"],
       [r"\bвыбери\b(?!.*\bчисло)", r"\bчто выбрать\b", r"\bво что поиграть\b.*(?:запусти|открой|включи)",
        r"^(?:запусти|открой|включи)\s+(?:мне\s+)?(?:что[- ]нибудь|случайн\w+)\s+из\b"],
       exclusive=True)
def choose_one(cmd, ctx):
    text = cmd.text_lower
    known = _known(ctx)

    launch = bool(re.search(r"\b(?:запусти|открой|включи|запускай)\b", text))
    # варианты идут после глагола или после слов «между / из / выбрать»
    m = (re.search(r"\b(?:запусти|открой|включи|запускай)\s+(?:мне\s+)?(?:одну из\s+|что[- ]нибудь из\s+)?(.+)$", text)
         or re.search(r"\b(?:между|из|выбери|выбрать)\s+(.+)$", text))
    options = split_options(m.group(1), known) if m else []
    options = [re.sub(r"^(?:мне|между)\s+", "", o) for o in options]

    if len(options) < 2:
        return ctx.reply("Назовите хотя бы два варианта, и я выберу")

    app_like = launch and all(_is_known(o, known) for o in options)
    if app_like:
        # запускаем случайную программу из установленных
        shuffled = random.sample(options, len(options))
        for choice in shuffled:
            if "не удалось найти" not in ctx.app_launcher.launch(choice, "").lower():
                return ctx.reply(f"Выбор пал на {choice}. Запускаю")
        return ctx.reply("Ничего из названного я не нашёл на компьютере")

    choice = random.choice(options)
    return ctx.reply(random.choice([
        f"Мой выбор: {choice}", f"Решено: {choice}", f"Однозначно: {choice}",
        f"Бросил жребий. Выпало: {choice}"]))


@skill(CATEGORY, "Предложить игру из установленных",
       ["во что поиграть", "посоветуй игру", "я не знаю во что поиграть"],
       [r"\bво что (?:бы )?(?:поиграть|сыграть)\b", r"посоветуй\s+(?:мне\s+)?игру"])
def suggest_game(cmd, ctx):
    from config.basic_apps import BASIC_APPS
    games = {"dota", "cs2", "roblox", "minecraft", "genshin", "valorant",
             "fortnite", "leagueoflegends"}
    installed = [item for item in BASIC_APPS if item["id"] in games
                 and any(ctx.app_launcher._from_memory(a.lower()) for a in item["aliases"])]
    if not installed:
        return ctx.reply("Не вижу установленных игр. Назовите варианты, и я выберу, например: запусти мне доту или майнкрафт")
    pick = random.choice(installed)["title"]
    return ctx.reply(f"Предлагаю поиграть в {pick}. Сказать «запусти {pick}»?")


